// The chroma format and bit depth of real parameter sets (H.264 and HEVC SPS
// of 1280x720 streams: 4:2:0, 4:4:4 and HEVC's 4:2:2, 8 and 10 bits; AV1
// sequence headers), through a configuration as packets carry it; malformed
// ones are refused.
#include "media/nal.hpp"
#include "media/sampling.hpp"
#include "support/check.hpp"

using namespace rcsdk;
using Bytes = std::vector<uint8_t>;

int main() {
    return runTest("sampling", [] {
        const Bytes h264_420_8{0x67, 0x64, 0x00, 0x1f, 0xac, 0xb2, 0x00, 0xa0, 0x0b, 0x76, 0x02, 0x20,
                               0x00, 0x00, 0x03, 0x00, 0x20, 0x00, 0x00, 0x07, 0x81, 0xe3, 0x06, 0x49};
        const Bytes h264_444_8{0x67, 0xf4, 0x00, 0x1f, 0x91, 0x96, 0x40, 0x14, 0x01, 0x6e, 0xc0, 0x44, 0x00,
                               0x00, 0x03, 0x00, 0x04, 0x00, 0x00, 0x03, 0x00, 0xf0, 0x3c, 0x60, 0xc9, 0x20};
        const Bytes h264_420_10{0x67, 0x6e, 0x00, 0x1f, 0xa6, 0xcb, 0x20, 0x0a, 0x00, 0xb7, 0x60, 0x22, 0x00,
                                0x00, 0x03, 0x00, 0x02, 0x00, 0x00, 0x03, 0x00, 0x78, 0x1e, 0x30, 0x64, 0x90};
        const Bytes h264_444_10{0x67, 0xf4, 0x00, 0x1f, 0x90, 0xd9, 0x64, 0x01, 0x40, 0x16, 0xec, 0x04, 0x40,
                                0x00, 0x00, 0x03, 0x00, 0x40, 0x00, 0x00, 0x0f, 0x03, 0xc6, 0x0c, 0x92};
        const Bytes h264_baseline{0x67, 0x42, 0xc0, 0x1f, 0xda, 0x01, 0x40, 0x16, 0xec, 0x04, 0x40, 0x00,
                                  0x00, 0x03, 0x00, 0x40, 0x00, 0x00, 0x0f, 0x03, 0xc6, 0x0c, 0x92};
        CHECK((h264Sampling(h264_420_8) == Sampling{1, 8}));
        CHECK((h264Sampling(h264_444_8) == Sampling{3, 8}));
        CHECK((h264Sampling(h264_420_10) == Sampling{1, 10}));
        CHECK((h264Sampling(h264_444_10) == Sampling{3, 10}));
        CHECK((h264Sampling(h264_baseline) == Sampling{1, 8})); // Profiles without the fields: 4:2:0, 8 bits.

        const Bytes hevc_420_8{0x42, 0x01, 0x01, 0x01, 0x60, 0x00, 0x00, 0x03, 0x00, 0x90, 0x00, 0x00, 0x03, 0x00,
                               0x00, 0x03, 0x00, 0x5d, 0xa0, 0x02, 0x80, 0x80, 0x2d, 0x16, 0x59, 0x2a, 0x49, 0x32,
                               0xbc, 0x05, 0xa0, 0x20, 0x00, 0x00, 0x03, 0x00, 0x20, 0x00, 0x00, 0x03, 0x03, 0xc1};
        const Bytes hevc_444_8{0x42, 0x01, 0x01, 0x04, 0x08, 0x00, 0x00, 0x03, 0x00, 0x9e, 0x08, 0x00, 0x00, 0x03,
                               0x00, 0x00, 0x5d, 0x90, 0x00, 0x50, 0x10, 0x05, 0xa2, 0xcb, 0x25, 0x49, 0x26, 0x57,
                               0x80, 0xb4, 0x04, 0x00, 0x00, 0x03, 0x00, 0x04, 0x00, 0x00, 0x03, 0x00, 0x78, 0x20};
        const Bytes hevc_444_10{0x42, 0x01, 0x01, 0x04, 0x08, 0x00, 0x00, 0x03, 0x00, 0x9c, 0x08, 0x00, 0x00, 0x03,
                                0x00, 0x00, 0x5d, 0x90, 0x00, 0x50, 0x10, 0x05, 0xa2, 0x6c, 0xb2, 0x54, 0x92, 0x65,
                                0x78, 0x0b, 0x40, 0x40, 0x00, 0x00, 0x03, 0x00, 0x40, 0x00, 0x00, 0x07, 0x82};
        const Bytes hevc_420_10{0x42, 0x01, 0x01, 0x02, 0x20, 0x00, 0x00, 0x03, 0x00, 0x90, 0x00, 0x00, 0x03,
                                0x00, 0x00, 0x03, 0x00, 0x5d, 0xa0, 0x02, 0x80, 0x80, 0x2d, 0x13, 0x65, 0x92,
                                0xa4, 0x93, 0x2b, 0xc0, 0x5a, 0x02, 0x00, 0x00, 0x03, 0x00, 0x02, 0x00, 0x00,
                                0x03, 0x00, 0x3c, 0x10};
        const Bytes hevc_422_10{0x42, 0x01, 0x01, 0x04, 0x08, 0x00, 0x00, 0x03, 0x00, 0x9d, 0x08, 0x00, 0x00, 0x03,
                                0x00, 0x00, 0x5d, 0xb0, 0x02, 0x80, 0x80, 0x2d, 0x13, 0x65, 0x92, 0xa4, 0x93, 0x2b,
                                0xc0, 0x5a, 0x02, 0x00, 0x00, 0x03, 0x00, 0x02, 0x00, 0x00, 0x03, 0x00, 0x3c, 0x10};
        CHECK((hevcSampling(hevc_420_8) == Sampling{1, 8}));
        CHECK((hevcSampling(hevc_444_8) == Sampling{3, 8}));
        CHECK((hevcSampling(hevc_444_10) == Sampling{3, 10}));
        CHECK((hevcSampling(hevc_420_10) == Sampling{1, 10}));
        CHECK((hevcSampling(hevc_422_10) == Sampling{2, 10}));

        // AV1: NVENC's 8-bit 4:2:0 header, and a 10-bit 4:2:0 one.
        const Bytes av1_420_8{0x0a, 0x0f, 0x00, 0x00, 0x00, 0x42, 0x62, 0x7f, 0xb3,
                              0xf0, 0x00, 0x86, 0x64, 0x08, 0x08, 0x04, 0x10};
        const Bytes av1_420_10{0x0a, 0x0b, 0x00, 0x00, 0x00, 0x2d, 0x4c, 0xff, 0xb3, 0xcc, 0xaf, 0x94, 0x04};
        CHECK((av1Sampling(av1_420_8) == Sampling{1, 8}));
        CHECK((av1Sampling(av1_420_10) == Sampling{1, 10}));

        // Through a configuration: the SPS among the parameter sets.
        Bytes config;
        nal::appendUnit(config, Bytes{0x40, 0x01, 0x0c}); // A VPS (not parsed).
        nal::appendUnit(config, hevc_444_10);
        nal::appendUnit(config, Bytes{0x44, 0x01, 0xc1}); // A PPS.
        CHECK((keyframeSampling(RCS_CODEC_HEVC, config, {}) == samplingOf(RCS_PICTURE_444_10)));
        CHECK((keyframeSampling(RCS_CODEC_HEVC, config, {}) == samplingOf(RCS_PICTURE_HDR10_444)));
        Bytes h264Config;
        nal::appendUnit(h264Config, h264_444_8);
        nal::appendUnit(h264Config, Bytes{0x68, 0xeb, 0xe3, 0xcb});
        CHECK((keyframeSampling(RCS_CODEC_H264, h264Config, {}) == samplingOf(RCS_PICTURE_444_8)));
        CHECK((keyframeSampling(RCS_CODEC_AV1, av1_420_10, {}) == samplingOf(RCS_PICTURE_HDR10_420)));
        CHECK(samplingText(Sampling{2, 10}) == "4:2:2 10-bit");

        // Malformed: no SPS, the wrong NAL type, truncated.
        Bytes noSps;
        nal::appendUnit(noSps, Bytes{0x68, 0xeb});
        CHECK(throws<Failure>([&] { keyframeSampling(RCS_CODEC_H264, noSps, {}); }));
        CHECK(throws<Failure>([&] { h264Sampling(hevc_420_8); }));
        CHECK(throws<Failure>([&] { hevcSampling(h264_420_8); }));
        CHECK(throws<Failure>([&] { hevcSampling(Bytes(hevc_420_8.begin(), hevc_420_8.begin() + 20)); }));
        CHECK(throws<Failure>([&] { h264Sampling(Bytes(h264_444_8.begin(), h264_444_8.begin() + 4)); }));
    });
}
