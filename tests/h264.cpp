// H.264 SPS rewriting.
#include "media/h264.hpp"
#include "support/check.hpp"

#include <random>

using namespace rcsdk;
using Bytes = std::vector<uint8_t>;

static void spsRewrite() {
    // Real VideoToolbox 1920x1080 High-profile SPS; the rewrite must declare
    // zero reordered pictures and one reference frame buffer in the VUI.
    const Bytes source{0x27, 0x64, 0x00, 0x2a, 0xac, 0x56, 0x80, 0x78, 0x02, 0x27, 0xe5, 0x40};
    const Bytes expected{0x27, 0x64, 0x00, 0x2a, 0xac, 0x56, 0x80, 0x78,
                         0x02, 0x27, 0xe5, 0x80, 0x6d, 0x04, 0x42, 0x35};
    CHECK(h264::noReorderingSps(source) == expected);
    CHECK(h264::noReorderingSps(expected) == expected); // Idempotent.
    // Existing aspect, colour, timing and HRD fields are preserved.
    const Bytes colorHrd{0x27, 0x64, 0x00, 0x2a, 0xac, 0x56, 0x80, 0x78, 0x02, 0x27, 0xe5, 0xff,
                         0xc0, 0x01, 0x00, 0x00, 0xfd, 0xc0, 0x40, 0x40, 0x7c, 0x00, 0x00, 0x03,
                         0x00, 0x04, 0x00, 0x00, 0x03, 0x01, 0xe3, 0x80, 0x7b, 0xde, 0xf8, 0x48};
    const Bytes preserved{0x27, 0x64, 0x00, 0x2a, 0xac, 0x56, 0x80, 0x78, 0x02, 0x27, 0xe5, 0xff, 0xc0, 0x01,
                          0x00, 0x00, 0xfd, 0xc0, 0x40, 0x40, 0x7c, 0x00, 0x00, 0x03, 0x00, 0x04, 0x00, 0x00,
                          0x03, 0x01, 0xe3, 0x80, 0x7b, 0xde, 0xf8, 0x5b, 0x41, 0x10, 0x8d, 0x40};
    CHECK(h264::noReorderingSps(colorHrd) == preserved);
    // An existing larger DPB capacity is kept.
    const Bytes reordered{0x27, 0x64, 0x00, 0x2a, 0xac, 0x56, 0x80, 0x78, 0x02,
                          0x27, 0xe5, 0x80, 0x6d, 0x04, 0x42, 0x2c, 0xb0};
    const Bytes restricted{0x27, 0x64, 0x00, 0x2a, 0xac, 0x56, 0x80, 0x78, 0x02,
                           0x27, 0xe5, 0x80, 0x6d, 0x04, 0x42, 0x32, 0xc0};
    CHECK(h264::noReorderingSps(reordered) == restricted);

    for (size_t i = 0; i < source.size(); ++i) {
        CHECK(throws<Failure>([&] { h264::noReorderingSps(std::span(source).first(i)); }));
    }
    Bytes pps = source;
    pps[0] = 0x28;
    CHECK(throws<Failure>([&] { h264::noReorderingSps(pps); }));
    // Random input is either rejected or rewritten to a bounded size.
    std::mt19937 random(923);
    for (int i = 0; i < 2000; ++i) {
        Bytes bytes(4 + random() % 60);
        for (auto& b : bytes) {
            b = uint8_t(random());
        }
        bytes[0] = 0x27;
        try {
            CHECK(h264::noReorderingSps(bytes).size() < 4096);
        } catch (const Failure&) {
        }
    }
}

int main() {
    return runTest("h264", [] { spsRewrite(); });
}
